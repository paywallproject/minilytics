// Refreshes src/worker/lib/referrer-spam.ts from Matomo's public-domain referrer spam list (the list Plausible uses).
// Run: node scripts/update-referrer-spam.mjs
import { writeFileSync } from 'node:fs';

const URL_ = 'https://raw.githubusercontent.com/matomo-org/referrer-spam-list/master/spammers.txt';
const res = await fetch(URL_);
if (!res.ok) throw new Error(`${URL_}: ${res.status}`);
const domains = [...new Set((await res.text()).split('\n').map((l) => l.trim().toLowerCase()).filter((l) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)))].sort();
if (domains.length < 1000) throw new Error(`only ${domains.length} domains; refusing to overwrite`);

writeFileSync(
  new globalThis.URL('../src/worker/lib/referrer-spam.ts', import.meta.url),
  `// Generated by scripts/update-referrer-spam.mjs from ${URL_} (public domain). Do not edit by hand.\n` +
    `export const SPAM_DOMAINS = new Set(${JSON.stringify(domains.join('\n'))}.split('\\n'));\n`,
);
console.log(`${domains.length} domains`);
